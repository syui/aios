#!/bin/bash
set -e
root=$(cd "$(dirname "$0")/.." && pwd)
CARCH=aarch64
PKGDEST=${PKGDEST:-}
if [ -z "$PACKAGER" ]; then
  name=$(git -C "$root" config user.name 2>/dev/null)
  mail=$(git -C "$root" config user.email 2>/dev/null)
  PACKAGER=${name:+$name${mail:+ <$mail>}}
  PACKAGER=${PACKAGER:-Unknown Packager}
fi
export CARCH PACKAGER

sha256() {
  if command -v sha256sum >/dev/null; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1
}

fetch_git() {
  local dir=$1 url=$2 frag=$3 ref
  case $frag in
    tag=*) ref=refs/tags/${frag#tag=} ;;
    commit=*) ref=${frag#commit=} ;;
    branch=*) ref=refs/heads/${frag#branch=} ;;
    '') ref=HEAD ;;
    *) echo "mkpkg: unknown fragment #$frag" >&2; return 1 ;;
  esac
  case $ref in
    HEAD|refs/heads/*)
      [ -f "$dir/.git/shallow" ] && rm -rf "$dir"
      [ -d "$dir/.git" ] || git init -q "$dir"
      git -C "$dir" fetch -q --filter=blob:none "$url" "$ref" ;;
    *)
      [ -d "$dir/.git" ] || git init -q "$dir"
      git -C "$dir" fetch -q --depth 1 "$url" "$ref" ;;
  esac
  git -C "$dir" checkout -q --force FETCH_HEAD
}

pkginfo() {
  local k=$1 v
  shift
  for v in "$@"; do
    [ -n "$v" ] && printf '%s = %s\n' "$k" "$v"
  done
  return 0
}

make_one() (
  startdir=$(cd "$1" && pwd)
  dest=$PKGDEST
  if [ -z "$dest" ]; then
    kind=$(basename "$(dirname "$startdir")")
    dest=$root/repo/$CARCH/$kind
  fi
  mkdir -p "$dest"
  cd "$startdir"
  source ./PKGBUILD
  work=$root/build/makepkg/$pkgname
  srcdir=$work/src
  pkgdir=$work/pkg
  export startdir srcdir pkgdir
  mkdir -p "$srcdir"
  rm -f "$srcdir/.c_deps" "$srcdir/.toolchain"

  i=0
  for s in "${source[@]}"; do
    want=${sha256sums[$i]:-SKIP}
    i=$((i + 1))
    name=
    src=$s
    case $s in *::*) name=${s%%::*}; src=${s#*::} ;; esac
    case $src in
      git+*)
        u=${src#git+}
        frag=
        case $u in *'#'*) frag=${u#*#}; u=${u%%#*} ;; esac
        [ -n "$name" ] || { name=${u##*/}; name=${name%.git}; }
        echo "==> $pkgname: $u ${frag}"
        fetch_git "$srcdir/$name" "$u" "$frag"
        ;;
      *://*)
        [ -n "$name" ] || name=${src##*/}
        if [ ! -f "$srcdir/$name" ]; then
          curl -fsSL --retry 4 --retry-all-errors --retry-delay 3 -o "$srcdir/$name.part" "$src" || {
            case $src in https://ftp.gnu.org/gnu/*) ;; *) exit 1 ;; esac
            echo "==> $pkgname: ftp.gnu.org failed, trying ftpmirror.gnu.org" >&2
            curl -fsSL --retry 4 --retry-all-errors --retry-delay 3 -o "$srcdir/$name.part" "https://ftpmirror.gnu.org/${src#https://ftp.gnu.org/gnu/}"
          }
          mv "$srcdir/$name.part" "$srcdir/$name"
        fi
        if [ "$want" != SKIP ] && [ "$(sha256 "$srcdir/$name")" != "$want" ]; then
          echo "mkpkg: $name: sha256 mismatch" >&2
          rm -f "$srcdir/$name"
          exit 1
        fi
        ;;
      *)
        [ -n "$name" ] || name=$src
        ln -sfn "$startdir/$src" "$srcdir/$name"
        ;;
    esac
  done

  if declare -F pkgver >/dev/null; then
    pkgver=$(cd "$srcdir" && pkgver)
  fi
  for f in prepare build; do
    if declare -F $f >/dev/null; then
      echo "==> $pkgname: $f()"
      (cd "$srcdir" && $f)
    fi
  done
  echo "==> $pkgname: package()"
  rm -rf "$pkgdir"
  mkdir -p "$pkgdir"
  (cd "$srcdir" && umask 022 && package)
  if [ -n "$install" ]; then
    cp "$startdir/$install" "$pkgdir/.INSTALL"
    chmod 644 "$pkgdir/.INSTALL"
  fi

  fullver=$pkgver-$pkgrel
  [ -n "$epoch" ] && [ "$epoch" != 0 ] && fullver=$epoch:$fullver
  pkgarch=$CARCH
  [ "${arch[*]}" = any ] && pkgarch=any
  size=$(du -sb --apparent-size "$pkgdir" | cut -f1)
  cdeps=()
  for f in "$srcdir/.c_deps" "$srcdir/.toolchain"; do
    if [ -f "$f" ]; then
      mapfile -t -O "${#cdeps[@]}" cdeps < "$f"
    fi
  done
  {
    echo "# Generated by aios bin/mkpkg.sh"
    pkginfo pkgname "$pkgname"
    pkginfo pkgbase "${pkgbase:-$pkgname}"
    pkginfo pkgver "$fullver"
    pkginfo pkgdesc "$pkgdesc"
    pkginfo url "$url"
    pkginfo builddate "$(date +%s)"
    pkginfo packager "$PACKAGER"
    pkginfo size "$size"
    pkginfo arch "$pkgarch"
    pkginfo license "${license[@]}"
    pkginfo replaces "${replaces[@]}"
    pkginfo conflict "${conflicts[@]}"
    pkginfo provides "${provides[@]}"
    pkginfo backup "${backup[@]}"
    pkginfo depend "${depends[@]}"
    pkginfo optdepend "${optdepends[@]}"
    pkginfo makedepend "${cdeps[@]}"
  } > "$pkgdir/.PKGINFO"

  rm -f "$dest/$pkgname"-[0-9]*-[0-9]*-"$pkgarch".pkg.tar.zst
  out=$dest/$pkgname-$fullver-$pkgarch.pkg.tar.zst
  cd "$pkgdir"
  mapfile -t top < <(LC_ALL=C ls -A | grep -vx '.PKGINFO')
  tar --numeric-owner --owner=0 --group=0 -cf - .PKGINFO "${top[@]}" | zstd -q -T0 -19 -f -o "$out"
  echo "==> made ${out#"$root"/}"
)

[ $# -gt 0 ] || { echo "usage: $0 pkg/rust/NAME | pkg/c/NAME ..." >&2; exit 1; }
for d in "$@"; do
  make_one "$d"
done
